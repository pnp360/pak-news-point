export function translateToEnglish(urduText: string): string {
  let result = urduText;
  const sorted = Object.entries(URDU_TO_ENGLISH).sort((a, b) => b[0].length - a[0].length);
  for (const [urdu, english] of sorted) {
    result = result.replace(new RegExp(urdu, 'g'), english);
  }
  return result;
}

const URDU_REGEX = /[\u0600-\u06FF\u0750-\u077F\uFB50-\uFDFF\uFE70-\uFEFF]/g;

export function translateToCleanEnglish(urduText: string): string {
  const translated = translateToEnglish(urduText);
  return translated.replace(URDU_REGEX, '').replace(/\s+/g, ' ').trim();
}

