function transliterateWord(word: string): string {
  if (!word) return word;
  const lower = word.toLowerCase();
  if (/^[a-z\d]+$/.test(lower) && /\d/.test(lower)) return word;
  const KEEP = new Set([
    'us','uk','un','eu','ai','tv','pc','5g','4g','psl','imf','odi',
    't20','icc','bcci','pcb','fifa','nato','who','wto','uae','usa',
  ]);
  if (KEEP.has(lower)) return lower.toUpperCase();

  const C: Record<string, string> = {
    'b':'ب','c':'ک','d':'ڈ','f':'ف','g':'گ',
    'h':'ہ','j':'ج','k':'ک','l':'ل','m':'م',
    'n':'ن','p':'پ','q':'ق','r':'ر','s':'س',
    't':'ٹ','v':'و','w':'و','x':'کس','z':'ز',
  };

  // Suffix patterns (applied first so they don't interfere with other rules)
  let w = lower;
  w = w.replace(/(?:tion|sion)$/, 'شن');
  w = w.replace(/ture$/, 'چر');
  w = w.replace(/dge$/, 'ج');
  w = w.replace(/ing$/, 'نگ');
  w = w.replace(/(?:ed|ied)$/, 'ڈ');
  w = w.replace(/er$/, 'ر');
  w = w.replace(/ly$/, 'لی');
  w = w.replace(/le$/, 'ل');
  w = w.replace(/([bdfgklmnprstvz])\1/g, '$1');

  // Now process char by char
  const M: [string, string][] = [
    ['th','تھ'], ['ch','چ'], ['sh','ش'],
    ['gh','گھ'], ['ph','ف'], ['qu','ق'],
    ['wh','و'], ['kn','ن'], ['ng','نگ'], ['mb','م'],
    ['oo','و'], ['ee','ی'], ['ea','یا'], ['oa','وا'],
    ['ai','ے'], ['ay','ے'], ['oi','وئ'], ['oy','وئ'],
    ['au','آ'], ['aw','آ'], ['ou','آو'], ['ow','آو'],
    ['ew','یو'], ['ie','ی'], ['ei','ی'],
    ['ua','وا'], ['ue','و'], ['ui','وئ'],
    ['ia','یا'], ['io','یو'],
  ];

  let result = '';
  let i = 0;
  while (i < w.length) {
    let matched = false;
    for (const [pat, rep] of M) {
      if (i + pat.length <= w.length && w.substring(i, i + pat.length) === pat) {
        result += rep; i += pat.length; matched = true; break;
      }
    }
    if (matched) continue;

    const ch = w[i]; i++;
    // Map vowels contextually
    if (ch === 'a') { result += result === '' ? 'ا' : 'ا'; continue; }
    if (ch === 'e') { // silent e - skip unless at start
      if (!result || (i < w.length)) { continue; }
      result += 'ی'; continue;
    }
    if (ch === 'i') { result += 'ی'; continue; }
    if (ch === 'o') { result += 'و'; continue; }
    if (ch === 'u') { result += 'و'; continue; }
    if (ch === 'y') { result += 'ی'; continue; }
    result += C[ch] || ch;
  }

  return result;
}

function stemWord(word: string): string | null {
  const attempts: string[] = [];
  const w = word;
  if (w.endsWith('ies') && w.length > 4) attempts.push(w.slice(0, -3) + 'y');
  if (w.endsWith('ves') && w.length > 4) attempts.push(w.slice(0, -3) + 'f');
  if (/(?:sh|ch|ss|o|x)es$/.test(w) && w.length > 4) attempts.push(w.slice(0, -2));
  if (w.endsWith('s') && !w.endsWith('ss') && w.length > 3) attempts.push(w.slice(0, -1));
  if (w.endsWith('ing') && w.length > 4) {
    let s = w.slice(0, -3);
    attempts.push(s);
    if (s.length > 2 && s.at(-1) === s.at(-2)) attempts.push(s.slice(0, -1));
    if (!s.endsWith('e')) attempts.push(s + 'e');
  }
  if (w.endsWith('ied') && w.length > 4) attempts.push(w.slice(0, -3) + 'y');
  if (w.endsWith('ed') && !w.endsWith('eed') && w.length > 3) {
    let s = w.slice(0, -2);
    attempts.push(s);
    if (!s.endsWith('e')) attempts.push(s + 'e');
  }
  for (const a of attempts) {
    if (a.length > 2 && ENGLISH_TO_URDU[a] !== undefined) return ENGLISH_TO_URDU[a];
  }
  return null;
}

export function translateToUrdu(englishText: string): string {
  const words = englishText.split(/\s+/);
  const result: string[] = [];
  for (const word of words) {
    const clean = word.replace(/[^a-zA-Z0-9\-']/g, '');
    const lower = clean.toLowerCase();
    const urdu = ENGLISH_TO_URDU[lower];
    if (urdu !== undefined) {
      result.push(word.replace(clean, urdu));
    } else {
      const stemmed = stemWord(lower);
      if (stemmed) {
        result.push(word.replace(clean, stemmed));
      } else {
        result.push(word.replace(clean, transliterateWord(clean)));
      }
    }
  }
  return result.filter(Boolean).join(' ');
}

const TWO_LETTER_KEEP = new Set(['ai', 'us', 'uk', 'eu', 'tv', 'pc', 'ceo', 'cfo', 'cto', '5g', '4g', 'psl', 'imf', 'cpec', 'odi', 't20']);

export function extractEnglishKeywords(text: string): string[] {
  const translated = translateToEnglish(text);
  const words = translated.split(/\s+/);
  const wordFreq: Record<string, number> = {};

  const stopWords = new Set([
    'the', 'a', 'an', 'in', 'of', 'to', 'and', 'is', 'are', 'was',
    'for', 'on', 'by', 'with', 'at', 'from', 'as', 'be', 'has', 'had',
    'its', 'but', 'not', 'or',
  ]);

  for (const word of words) {
    const cleaned = word.replace(/[^a-zA-Z0-9]/g, '').toLowerCase();
    if (!cleaned || stopWords.has(cleaned)) continue;
    if (cleaned.length < 3 && !TWO_LETTER_KEEP.has(cleaned)) continue;
    wordFreq[cleaned] = (wordFreq[cleaned] || 0) + 1;
  }

  return Object.entries(wordFreq)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 6)
    .map(([word]) => word);
}
